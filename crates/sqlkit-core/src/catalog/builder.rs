/// A database object name with its original identifier spelling preserved.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CatalogObjectName {
    schema: Option<String>,
    name: String,
}

impl CatalogObjectName {
    /// Construct an unqualified object name.
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            schema: None,
            name: name.into(),
        }
    }

    /// Construct a schema-qualified object name.
    pub fn qualified(schema: impl Into<String>, name: impl Into<String>) -> Self {
        Self {
            schema: Some(schema.into()),
            name: name.into(),
        }
    }

    /// Return the preserved schema spelling, if one was provided.
    pub fn schema(&self) -> Option<&str> {
        self.schema.as_deref()
    }

    /// Return the preserved bare object-name spelling.
    pub fn name(&self) -> &str {
        &self.name
    }

    fn normalized_key(&self, object_kind: &str) -> Result<String, SqlkitError> {
        let name = normalized_identifier(&self.name, object_kind)?;
        match &self.schema {
            Some(schema) => Ok(format!("{}.{}", normalized_identifier(schema, "schema")?, name)),
            None => Ok(name),
        }
    }
}

/// Whether an inspected relation is a base table or a view.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelationKind {
    /// A base table.
    Table,
    /// A view.
    View,
}

/// The persistence mode reported for a generated column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GeneratedColumnKind {
    /// The engine computes the value when the row is read.
    Virtual,
    /// The engine persists the computed value with the row.
    Stored,
}

/// An inspected column definition.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnDefinition {
    name: String,
    raw_sql_type: String,
    nullable: bool,
    default: Option<String>,
    primary_key: bool,
    resolved_sql_type: Option<String>,
    generated: Option<GeneratedColumnKind>,
    facts: InspectedFacts,
}

impl ColumnDefinition {
    /// Construct a column using the database-reported type and nullability.
    pub fn new(name: impl Into<String>, raw_sql_type: impl Into<String>, nullable: bool) -> Self {
        Self {
            name: name.into(),
            raw_sql_type: raw_sql_type.into(),
            nullable,
            default: None,
            primary_key: false,
            resolved_sql_type: None,
            generated: None,
            facts: InspectedFacts::default(),
        }
    }

    /// Attach the database-reported default expression.
    #[must_use]
    pub fn default(mut self, default: impl Into<String>) -> Self {
        self.default = Some(default.into());
        self
    }

    /// Mark this column as part of the primary key.
    #[must_use]
    pub fn primary_key(mut self) -> Self {
        self.primary_key = true;
        self
    }

    /// Supply the catalog type when the database reports an empty or engine-specific raw type.
    #[must_use]
    pub fn resolved_sql_type(mut self, sql_type: impl Into<String>) -> Self {
        self.resolved_sql_type = Some(sql_type.into());
        self
    }

    /// Mark the column as generated by the database.
    #[must_use]
    pub fn generated(mut self, kind: GeneratedColumnKind) -> Self {
        self.generated = Some(kind);
        self
    }

    /// Attach a `CHECK` constraint that constrains this column alone.
    #[must_use]
    pub fn check(mut self, check: CheckDefinition) -> Self {
        self.facts.checks.push(check);
        self
    }

    /// Attach the collation the column declares, when it differs from its
    /// type's.
    #[must_use]
    pub fn collation(mut self, collation: impl Into<String>) -> Self {
        self.facts.collation = Some(collation.into());
        self
    }

    /// Attach the column's `COMMENT ON` text.
    #[must_use]
    pub fn comment(mut self, comment: impl Into<String>) -> Self {
        self.facts.comment = Some(comment.into());
        self
    }
}

/// An inspected `CHECK` constraint on one column or on a domain.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckDefinition {
    name: String,
    expression: String,
    validated: bool,
}

impl CheckDefinition {
    /// A validated check named `name` (PostgreSQL's `conname`), whose
    /// expression is `expression` as PostgreSQL prints it (`pg_get_expr`).
    pub fn new(name: impl Into<String>, expression: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            expression: expression.into(),
            validated: true,
        }
    }

    /// Mark the check added `NOT VALID` and not validated since.
    #[must_use]
    pub fn not_valid(mut self) -> Self {
        self.validated = false;
        self
    }
}

/// What an inspected column or domain declares about its values beyond its
/// type: its checks, `COLLATE` and comment.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct InspectedFacts {
    checks: Vec<CheckDefinition>,
    collation: Option<String>,
    comment: Option<String>,
}

