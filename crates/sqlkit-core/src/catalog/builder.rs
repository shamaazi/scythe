/// Validates inspected schema definitions before constructing a [`Catalog`].
///
/// Columns and domains record the value constraints the database reports
/// (their `CHECK`s, `COLLATE` and `COMMENT ON` text, see
/// [`ColumnDefinition::check`] and [`DomainDefinition::check`]) and the
/// `varchar(n)`/`char(n)` length of their type, as the same schema parsed
/// from DDL records them (see [`super::ColumnConstraints`]).
#[derive(Debug, Default)]
pub struct CatalogBuilder {
    search_path: Option<Vec<String>>,
    relations: Vec<RelationDefinition>,
    enums: Vec<EnumDefinition>,
    composites: Vec<CompositeDefinition>,
    domains: Vec<DomainDefinition>,
    functions: Vec<FunctionDefinition>,
}

impl CatalogBuilder {
    /// Start an empty catalog builder.
    pub fn new() -> Self {
        Self::default()
    }

    /// Register the ordered schemas used to resolve unqualified object names.
    #[must_use]
    pub fn search_path<I, S>(mut self, schemas: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.search_path = Some(schemas.into_iter().map(Into::into).collect());
        self
    }

    /// Add a table or view definition.
    #[must_use]
    pub fn relation(mut self, definition: RelationDefinition) -> Self {
        self.relations.push(definition);
        self
    }

    /// Add an enum definition.
    #[must_use]
    pub fn enum_type(mut self, definition: EnumDefinition) -> Self {
        self.enums.push(definition);
        self
    }

    /// Add a composite definition.
    #[must_use]
    pub fn composite(mut self, definition: CompositeDefinition) -> Self {
        self.composites.push(definition);
        self
    }

    /// Add a domain definition.
    #[must_use]
    pub fn domain(mut self, definition: DomainDefinition) -> Self {
        self.domains.push(definition);
        self
    }

    #[must_use]
    pub fn function(mut self, definition: FunctionDefinition) -> Self {
        self.functions.push(definition);
        self
    }

    /// Validate all definitions and construct the catalog.
    pub fn build(self) -> Result<Catalog, SqlkitError> {
        let mut catalog = Catalog {
            tables: AHashMap::new(),
            enums: AHashMap::new(),
            composites: AHashMap::new(),
            domains: AHashMap::new(),
            functions: AHashMap::new(),
            search_path: normalize_search_path(self.search_path)?,
            relation_names: AHashMap::new(),
            relation_kinds: AHashMap::new(),
            raw_column_types: AHashMap::new(),
            generated_column_kinds: AHashMap::new(),
            enum_names: AHashMap::new(),
            composite_names: AHashMap::new(),
            domain_names: AHashMap::new(),
            raw_domain_types: AHashMap::new(),
            view_queries: Vec::new(),
        };

        let mut pending = add_relations(&mut catalog, self.relations)?;
        add_enums(&mut catalog, self.enums)?;
        add_composites(&mut catalog, self.composites)?;
        pending.extend(add_domains(&mut catalog, self.domains)?);
        // Once every domain exists: a column or domain typed with one takes
        // its facts from it.
        apply_facts(&mut catalog, pending);
        add_functions(&mut catalog, self.functions)?;
        Ok(catalog)
    }
}

fn add_functions(catalog: &mut Catalog, definitions: Vec<FunctionDefinition>) -> Result<(), SqlkitError> {
    for definition in definitions {
        let key = definition.name.normalized_key("function")?;
        let arguments = definition
            .arguments
            .into_iter()
            .map(|argument| {
                Ok(FunctionArgument {
                    name: argument.name,
                    sql_type: normalized_sql_type(&argument.raw_sql_type, "function argument type")?,
                    mode: argument.mode,
                    has_default: argument.has_default,
                })
            })
            .collect::<Result<Vec<_>, SqlkitError>>()?;
        let return_type = match definition.return_type {
            FunctionReturnDefinition::Scalar(sql_type) => FunctionReturn::Scalar {
                sql_type: normalized_sql_type(&sql_type, "function return type")?,
                nullable: true,
            },
            FunctionReturnDefinition::SetOf(sql_type) => FunctionReturn::SetOf {
                sql_type: normalized_sql_type(&sql_type, "function return type")?,
                nullable: true,
            },
            FunctionReturnDefinition::Table(columns) => FunctionReturn::Table {
                columns: columns
                    .into_iter()
                    .map(|column| {
                        Ok(FunctionResultColumn {
                            name: column.name,
                            sql_type: normalized_sql_type(&column.raw_sql_type, "function result type")?,
                            nullable: column.nullable,
                        })
                    })
                    .collect::<Result<Vec<_>, SqlkitError>>()?,
            },
        };
        let function = Function {
            arguments,
            return_type,
            strict: false,
            body: None,
        };
        let overloads = catalog.functions.entry(key.clone()).or_default();
        let signature = function
            .arguments
            .iter()
            .filter(|argument| argument.mode != FunctionArgumentMode::Out)
            .map(|argument| argument.sql_type.as_str())
            .collect::<Vec<_>>();
        if overloads.iter().any(|existing| {
            existing
                .arguments
                .iter()
                .filter(|argument| argument.mode != FunctionArgumentMode::Out)
                .map(|argument| argument.sql_type.as_str())
                .eq(signature.iter().copied())
        }) {
            return Err(duplicate_error("function signature", &key));
        }
        overloads.push(function);
    }
    Ok(())
}

fn add_relations(
    catalog: &mut Catalog,
    definitions: Vec<RelationDefinition>,
) -> Result<Vec<PendingFacts>, SqlkitError> {
    let mut pending = Vec::new();
    for definition in definitions {
        let key = definition.name.normalized_key("relation")?;
        if catalog.tables.contains_key(&key) {
            return Err(duplicate_error("relation", &key));
        }

        let mut column_names = AHashSet::new();
        let mut columns = Vec::with_capacity(definition.columns.len());
        let mut raw_types = AHashMap::new();
        let mut generated_kinds = AHashMap::new();
        for column in definition.columns {
            let column_key = normalized_identifier(&column.name, "column")?;
            if !column_names.insert(column_key.clone()) {
                return Err(duplicate_error("column", &format!("{key}.{column_key}")));
            }
            let sql_type_source = column.resolved_sql_type.as_deref().unwrap_or(&column.raw_sql_type);
            let sql_type = normalized_sql_type(sql_type_source, "column type")?;
            if let Some(kind) = column.generated {
                generated_kinds.insert(column_key.clone(), kind);
            }
            pending.push(PendingFacts {
                target: FactsTarget::Column(key.clone(), columns.len()),
                owner: definition.name.name.clone(),
                raw_type: column.raw_sql_type.clone(),
                facts: column.facts,
            });
            raw_types.insert(column_key, column.raw_sql_type);
            columns.push(Column {
                name: column.name,
                sql_type,
                nullable: column.nullable,
                default: column.default,
                primary_key: column.primary_key,
                constraints: ColumnConstraints::default(),
            });
        }

        catalog
            .tables
            .insert(key.clone(), Table::new(columns, definition.name.name.clone()));
        catalog.relation_names.insert(key.clone(), definition.name);
        catalog.relation_kinds.insert(key.clone(), definition.kind);
        catalog.raw_column_types.insert(key.clone(), raw_types);
        if !generated_kinds.is_empty() {
            catalog.generated_column_kinds.insert(key, generated_kinds);
        }
    }
    Ok(pending)
}

fn add_enums(catalog: &mut Catalog, definitions: Vec<EnumDefinition>) -> Result<(), SqlkitError> {
    for definition in definitions {
        let key = definition.name.normalized_key("enum")?;
        if catalog.enums.contains_key(&key) {
            return Err(duplicate_error("enum", &key));
        }
        catalog.enums.insert(
            key.clone(),
            EnumType {
                values: definition.values,
            },
        );
        catalog.enum_names.insert(key, definition.name);
    }
    Ok(())
}

fn add_composites(catalog: &mut Catalog, definitions: Vec<CompositeDefinition>) -> Result<(), SqlkitError> {
    for definition in definitions {
        let key = definition.name.normalized_key("composite")?;
        if catalog.composites.contains_key(&key) || catalog.enums.contains_key(&key) {
            return Err(duplicate_error("type", &key));
        }
        let mut field_names = AHashSet::new();
        let mut fields = Vec::with_capacity(definition.fields.len());
        for field in definition.fields {
            let field_key = normalized_identifier(&field.name, "composite field")?;
            if !field_names.insert(field_key.clone()) {
                return Err(duplicate_error("composite field", &format!("{key}.{field_key}")));
            }
            fields.push(CompositeField {
                name: field.name,
                sql_type: normalized_sql_type(&field.raw_sql_type, "composite field type")?,
                nullable: field.nullable,
            });
        }
        catalog.composites.insert(key.clone(), CompositeType { fields });
        catalog.composite_names.insert(key, definition.name);
    }
    Ok(())
}

fn add_domains(catalog: &mut Catalog, definitions: Vec<DomainDefinition>) -> Result<Vec<PendingFacts>, SqlkitError> {
    let mut pending = Vec::new();
    for definition in definitions {
        let key = definition.name.normalized_key("domain")?;
        if catalog.domains.contains_key(&key)
            || catalog.enums.contains_key(&key)
            || catalog.composites.contains_key(&key)
        {
            return Err(duplicate_error("type", &key));
        }
        let base_type = normalized_sql_type(&definition.raw_base_type, "domain base type")?;
        catalog.domains.insert(
            key.clone(),
            DomainDef {
                base_type,
                not_null: definition.not_null,
                constraints: ColumnConstraints::default(),
                other_constraints: Vec::new(),
            },
        );
        pending.push(PendingFacts {
            target: FactsTarget::Domain(key.clone()),
            owner: definition.name.name.clone(),
            raw_type: definition.raw_base_type.clone(),
            facts: definition.facts,
        });
        catalog.domain_names.insert(key.clone(), definition.name);
        catalog.raw_domain_types.insert(key, definition.raw_base_type);
    }
    Ok(pending)
}

/// What an inspected column or domain declares, waiting for every domain to
/// be added.
struct PendingFacts {
    target: FactsTarget,
    /// The relation's or domain's name, unqualified, as the database spells it.
    owner: String,
    /// The column's type or the domain's base type, as the database reports it.
    raw_type: String,
    facts: InspectedFacts,
}

enum FactsTarget {
    /// A relation's key and the column's index.
    Column(String, usize),
    /// A domain's key.
    Domain(String),
}

/// Record inspected facts as the DDL path records the same schema's: the
/// length of a `varchar(n)`/`char(n)` type and the domain a type names come
/// from the type, and checks are read as [`super::constraints::inspected_check`]
/// reads them.
fn apply_facts(catalog: &mut Catalog, pending: Vec<PendingFacts>) {
    for PendingFacts {
        target,
        owner,
        raw_type,
        facts,
    } in pending
    {
        let mut constraints = sqlparser::parser::Parser::new(&sqlparser::dialect::PostgreSqlDialect {})
            .try_with_sql(&raw_type)
            .and_then(|mut parser| parser.parse_data_type())
            .map(|data_type| ColumnConstraints::from_type(&data_type, &[], &catalog.domains))
            .unwrap_or_default();
        let base_type = resolved_base_type(catalog, &raw_type);
        constraints.collation = facts.collation.map(|collation| collation.to_lowercase());
        constraints.comment = facts.comment;
        let slot = match &target {
            FactsTarget::Column(key, index) => catalog
                .tables
                .get_mut(key)
                .and_then(|table| table.columns.get_mut(*index))
                .map(|column| (Some(column.name.clone()), &mut column.constraints)),
            FactsTarget::Domain(key) => catalog
                .domains
                .get_mut(key)
                .map(|domain| (None, &mut domain.constraints)),
        };
        let Some((column, slot)) = slot else {
            continue;
        };
        constraints.checks = facts
            .checks
            .iter()
            .map(|check| {
                super::constraints::inspected_check(
                    &check.name,
                    &owner,
                    column.as_deref(),
                    &check.expression,
                    check.validated,
                    base_type.as_deref(),
                )
            })
            .collect();
        *slot = constraints;
    }
}

/// `raw_type` with every domain it names resolved to the type underneath,
/// normalized as the DDL path normalizes a type.
fn resolved_base_type(catalog: &Catalog, raw_type: &str) -> Option<String> {
    let parse = |sql: &str| {
        sqlparser::parser::Parser::new(&sqlparser::dialect::PostgreSqlDialect {})
            .try_with_sql(sql)
            .and_then(|mut parser| parser.parse_data_type())
            .ok()
    };
    let mut data_type = parse(raw_type)?;
    // Bounded: a domain cannot be its own base, but the catalog is input.
    for _ in 0..16 {
        let sqlparser::ast::DataType::Custom(name, _) = &data_type else {
            break;
        };
        let key = super::type_normalizer::object_name_to_key(name);
        let Some(base) = catalog.raw_domain_types.get(&key) else {
            break;
        };
        data_type = parse(base)?;
    }
    Some(super::type_normalizer::normalize_data_type(&data_type, &AHashMap::new()).0)
}

fn normalize_search_path(search_path: Option<Vec<String>>) -> Result<Option<Vec<String>>, SqlkitError> {
    search_path
        .map(|schemas| {
            schemas
                .into_iter()
                .map(|schema| normalized_identifier(&schema, "search path schema"))
                .collect()
        })
        .transpose()
}

fn normalized_identifier(value: &str, description: &str) -> Result<String, SqlkitError> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        return Err(SqlkitError::invalid_config(format!(
            "invalid catalog: {description} must not be empty"
        )));
    }
    Ok(trimmed.to_lowercase())
}

fn normalized_sql_type(value: &str, description: &str) -> Result<String, SqlkitError> {
    normalized_identifier(value, description)
}

fn duplicate_error(object_kind: &str, key: &str) -> SqlkitError {
    SqlkitError::invalid_config(format!("invalid catalog: duplicate {object_kind} `{key}`"))
}

